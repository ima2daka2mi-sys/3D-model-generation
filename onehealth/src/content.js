// Titles by overall result (multi-ending, doc 5.5)
export function rankFor(rate, allGold) {
  if (allGold) return { title: 'ワンヘルスマスター', text: 'すべてのテーマでゴールドスタンプを獲得！ 人・動物・環境のつながりを理解した、ワンヘルスの達人です。' };
  if (rate >= 0.8) return { title: 'ワンヘルス・エキスパート', text: 'あと少しでマスター！ シルバーのテーマに再挑戦して、ゴールドを目指そう。' };
  if (rate >= 0.5) return { title: 'ワンヘルス・チャレンジャー', text: '基本はばっちり。まちがえた問題をもう一度体験して、知識を確かなものにしよう。' };
  return { title: 'ワンヘルス・ビギナー', text: 'ワンヘルスの世界への第一歩。もう一度めぐって、ゴールドスタンプを目指そう！' };
}
